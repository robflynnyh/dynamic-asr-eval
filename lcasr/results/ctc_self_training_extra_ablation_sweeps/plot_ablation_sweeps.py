def ensure_summary(refresh: bool) -> None:
    if refresh or not SUMMARY_CSV.exists():
        subprocess.run(["python", str(ROOT / "aggregate.py")], cwd=ROOT, check=True)


def load_rows() -> list[dict[str, str]]:
    with SUMMARY_CSV.open(newline="") as f:
        rows = list(csv.DictReader(f))
    return [row for row in rows if not row.get("error")]


def load_baseline_wer() -> dict[str, float]:
    if CROSSDATASET_BASELINE.exists():
        with CROSSDATASET_BASELINE.open("rb") as f:
            data = pickle.load(f)
        return {
            str(data["dataset_a"]): float(data["a_baseline"]["wer"]),
            str(data["dataset_b"]): float(data["b_baseline"]["wer"]),
        }
    return FALLBACK_BASELINE_WER.copy()


def ordered_settings(group: str, rows: list[dict[str, str]]) -> list[str]:
    present = {row["setting"] for row in rows if row["group"] == group}
    ordered = [setting for setting in SETTING_ORDER[group] if setting in present]
    extras = sorted(present.difference(ordered))
    return ordered + extras


def plot_group(
    group: str,
    rows: list[dict[str, str]],
    out_path: Path,
    selected_lrs: list[str],
    baseline_wer: dict[str, float],
) -> None:
    settings = ordered_settings(group, rows)
    datasets = [
        dataset
        for dataset in ("earnings22", "tedlium")
        if any(row["group"] == group and row["dataset"] == dataset for row in rows)
    ]
    if not datasets:
        raise SystemExit(f"No rows found for group={group}")

    fig_width = max(6.0, min(11.5, 1.0 + 0.95 * len(settings)))
    fig, axes = plt.subplots(
        1,
        len(datasets),
        figsize=(fig_width, 3.9),
        squeeze=False,
        constrained_layout=True,
    )

    for ax, dataset in zip(axes[0], datasets):
        subset = [
            row
            for row in rows
            if row["group"] == group and row["dataset"] == dataset
        ]
        lrs = [lr for lr in selected_lrs if any(row["lr"] == lr for row in subset)]
        repeated_values: dict[tuple[str, str], list[float]] = defaultdict(list)
        for row in subset:
            if row.get("wer") and row["lr"] in selected_lrs:
                repeated_values[(row["setting"], row["lr"])].append(float(row["wer"]) * 100.0)
        values = {
            key: {
                "mean": statistics.mean(vals),
                "std": statistics.stdev(vals) if len(vals) > 1 else 0.0,
                "n": len(vals),
            }
            for key, vals in repeated_values.items()
        }
        finite_values = [
            stat["mean"]
            for stat in values.values()
            if np.isfinite(stat["mean"])
        ]
        if not finite_values:
            continue
        lower_values = [stat["mean"] - stat["std"] for stat in values.values()]
        upper_values = [stat["mean"] + stat["std"] for stat in values.values()]
        value_range = max(upper_values) - min(lower_values)
        label_offset = max(0.015, value_range * 0.06)

        x = np.arange(len(settings))
        width = min(0.72 / max(len(lrs), 1), 0.28)
        offsets = (np.arange(len(lrs)) - (len(lrs) - 1) / 2.0) * width

        for idx, lr in enumerate(lrs):
            stats = [values.get((setting, lr)) for setting in settings]
            heights = [stat["mean"] if stat else np.nan for stat in stats]
            errors = [stat["std"] if stat else 0.0 for stat in stats]
            bars = ax.bar(
                x + offsets[idx],
                heights,
                width,
                yerr=errors if any(error > 0 for error in errors) else None,
                capsize=2 if any(error > 0 for error in errors) else 0,
                label=f"lr={LR_PRETTY[lr]}",
                color=COLORS[lr],
                edgecolor="black",
                linewidth=0.5,
            )
            for bar, height in zip(bars, heights):
                if np.isnan(height):
                    continue
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    height + label_offset,
                    f"{height:.1f}",
                    ha="center",
                    va="bottom",
                    fontsize=7,
                    rotation=90 if len(settings) > 6 else 0,
                )

        lower_pad = max(0.04, value_range * 0.25)
        upper_pad = max(0.10, value_range * 0.45)
        ymin = max(0.0, min(lower_values) - lower_pad)
        ymax = max(upper_values) + upper_pad
        ax.set_ylim(ymin, ymax)
        ax.set_title(DATASET_TITLES.get(dataset, dataset), fontsize=10)
        baseline = baseline_wer.get(dataset)
        if baseline is not None:
            ax.text(
                0.98,
                0.96,
                f"unadapted WER={baseline * 100:.1f}%",
                transform=ax.transAxes,
                ha="right",
                va="top",
                fontsize=8,
                color="#C44E52",
                bbox={"facecolor": "white", "edgecolor": "none", "alpha": 0.85, "pad": 1.5},
            )
        ax.set_xticks(x)
        labels = [SETTING_LABELS.get(setting, setting) for setting in settings]
        if group == "progressive_bottom":
            labels = [
                "train sub. only" if setting == "train-subsampling-only" else label
                for setting, label in zip(settings, labels)
            ]
        if group == "progressive_bottom_ctc_decoder":
            labels = [
                "train sub.\n+ ctc" if setting == "train-subsampling-only" else f"{label}\n+ ctc"
                for setting, label in zip(settings, labels)
            ]
        if group in {"progressive_top", "progressive_bottom", "progressive_bottom_ctc_decoder", "train_only", "layer_drop_lr_sweep"}:
            ax.set_xticklabels(labels, fontsize=8, rotation=35, ha="right")
        else:
            ax.set_xticklabels(labels, fontsize=8)
        ax.set_ylabel("WER (%)")
        ax.yaxis.grid(True, alpha=0.3)
        ax.set_axisbelow(True)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        if len(lrs) > 1:
            ax.legend(frameon=False, fontsize=8, loc="best")

    # fig.suptitle(GROUP_TITLES[group], fontsize=12)
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved {out_path}")


def plot_progressive_bottom_ctc_comparison(
    rows: list[dict[str, str]],
    out_path: Path,
    selected_lrs: list[str],
    baseline_wer: dict[str, float],
) -> None:
    if len(selected_lrs) != 1:
        raise SystemExit("progressive_bottom_ctc_comparison expects exactly one learning rate")
    selected_lr = selected_lrs[0]
    settings = [
        setting
        for setting in SETTING_ORDER["progressive_bottom"]
        if any(
            row["group"] in {"progressive_bottom", "progressive_bottom_ctc_decoder"}
            and row["setting"] == setting
            and row["lr"] == selected_lr
            for row in rows
        )
    ]
    datasets = [
        dataset
        for dataset in ("earnings22", "tedlium")
        if any(
            row["group"] in {"progressive_bottom", "progressive_bottom_ctc_decoder"}
            and row["dataset"] == dataset
            and row["lr"] == selected_lr
            for row in rows
        )
    ]
    if not settings or not datasets:
        raise SystemExit("No rows found for progressive_bottom_ctc_comparison")

    fig_width = max(7.2, min(12.0, 1.2 + 1.05 * len(settings)))
    fig, axes = plt.subplots(
        1,
        len(datasets),
        figsize=(fig_width, 4.0),
        squeeze=False,
        constrained_layout=True,
    )

    for ax, dataset in zip(axes[0], datasets):
        repeated_values: dict[tuple[str, str], list[float]] = defaultdict(list)
        for row in rows:
            for variant, spec in PROGRESSIVE_BOTTOM_CTC_COMPARISON.items():
                if (
                    row["group"] == spec["group"]
                    and row["dataset"] == dataset
                    and row["lr"] == selected_lr
                    and row.get("wer")
                ):
                    repeated_values[(row["setting"], variant)].append(float(row["wer"]) * 100.0)

        values = {
            key: {
                "mean": statistics.mean(vals),
                "std": statistics.stdev(vals) if len(vals) > 1 else 0.0,
                "n": len(vals),
            }
            for key, vals in repeated_values.items()
        }
        finite_values = [
            stat["mean"]
            for stat in values.values()
            if np.isfinite(stat["mean"])
        ]
        if not finite_values:
            continue

        lower_values = [stat["mean"] - stat["std"] for stat in values.values()]
        upper_values = [stat["mean"] + stat["std"] for stat in values.values()]
        value_range = max(upper_values) - min(lower_values)
        label_offset = max(0.015, value_range * 0.06)

        x = np.arange(len(settings))
        variants = list(PROGRESSIVE_BOTTOM_CTC_COMPARISON)
        width = 0.32
        offsets = (np.arange(len(variants)) - (len(variants) - 1) / 2.0) * width

        for idx, variant in enumerate(variants):
            stats = [values.get((setting, variant)) for setting in settings]
            heights = [stat["mean"] if stat else np.nan for stat in stats]
            errors = [stat["std"] if stat else 0.0 for stat in stats]
            bars = ax.bar(
                x + offsets[idx],
                heights,
                width,
                yerr=errors if any(error > 0 for error in errors) else None,
                capsize=2 if any(error > 0 for error in errors) else 0,
                label=PROGRESSIVE_BOTTOM_CTC_COMPARISON[variant]["label"],
                color=COMPARISON_COLORS[variant],
                edgecolor="black",
                linewidth=0.5,
            )
            for bar, height in zip(bars, heights):
                if np.isnan(height):
                    continue
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    height + label_offset,
                    f"{height:.1f}",
                    ha="center",
                    va="bottom",
                    fontsize=7,
                    rotation=90,
                )

        lower_pad = max(0.04, value_range * 0.25)
        upper_pad = max(0.10, value_range * 0.45)
        ax.set_ylim(max(0.0, min(lower_values) - lower_pad), max(upper_values) + upper_pad)
        ax.set_title(DATASET_TITLES.get(dataset, dataset), fontsize=10)
        baseline = baseline_wer.get(dataset)
        if baseline is not None:
            ax.text(
                0.98,
                0.96,
                f"unadapted WER={baseline * 100:.1f}%",
                transform=ax.transAxes,
                ha="right",
                va="top",
                fontsize=8,
                color="#C44E52",
                bbox={"facecolor": "white", "edgecolor": "none", "alpha": 0.85, "pad": 1.5},
            )
        labels = [
            "train sub. only" if setting == "train-subsampling-only" else SETTING_LABELS.get(setting, setting)
            for setting in settings
        ]
        ax.set_xticks(x)
        ax.set_xticklabels(labels, fontsize=8, rotation=35, ha="right")
        ax.set_ylabel("WER (%)")
        ax.yaxis.grid(True, alpha=0.3)
        ax.set_axisbelow(True)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.legend(frameon=False, fontsize=8, loc="best")

    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--groups",
        nargs="+",
        default=[
            "train_only",
            "progressive_top",
            "progressive_bottom",
            "progressive_bottom_ctc_decoder",
            "progressive_bottom_ctc_comparison",
            "layer_type",
            "layer_drop_lr_sweep",
        ],
        choices=sorted(GROUP_TITLES),
    )
    parser.add_argument(
        "--lrs",
        nargs="+",
        default=["9e-5"],
        choices=sorted(LR_TAG),
        help="Learning rates to plot. Defaults to 9e-5 only.",
    )
    parser.add_argument("--refresh", action="store_true", help="Regenerate summary.csv first.")
    args = parser.parse_args()

    ensure_summary(refresh=args.refresh)
    rows = load_rows()
    selected_lrs = [LR_TAG[lr] for lr in args.lrs]
    baseline_wer = load_baseline_wer()
    for group in args.groups:
        if group == "progressive_bottom_ctc_comparison":
            plot_progressive_bottom_ctc_comparison(
                rows,
                ROOT / "progressive_bottom_ctc_comparison_ablation_bars.pdf",
                selected_lrs,
                baseline_wer,
            )
            continue
        if not any(row["group"] == group for row in rows):
            print(f"Skipping {group}: no rows found")
            continue
        plot_group(group, rows, ROOT / f"{group}_ablation_bars.pdf", selected_lrs, baseline_wer)


if __name__ == "__main__":
    main()
